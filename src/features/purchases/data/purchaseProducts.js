// PDF 7, 62: reorder tavsiya — kam qolgan tovarlar taklif etiladi
export const getReorderSuggestions = (products = purchaseProducts) =>
  products
    .filter((product) => product.stock <= product.reorderPoint)
    .map((product) => ({
      ...product,
      suggestedQty: Math.max(product.reorderPoint * 2 - product.stock, product.moq),
    }))
    .sort((a, b) => a.stock / a.reorderPoint - b.stock / b.reorderPoint);
